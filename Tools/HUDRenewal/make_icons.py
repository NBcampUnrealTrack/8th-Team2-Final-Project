def grid(text):
    rows = [r for r in text.strip('\n').split('\n')]
    w = max(len(r) for r in rows)
    return [r.ljust(w, '.') for r in rows]


def render(rows, scale=SCALE, pad=1):
    h, w = len(rows), len(rows[0])
    size = max(h, w) + pad * 2
    im = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    ox, oy = (size - w) // 2, (size - h) // 2
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in INK:
                im.putpixel((ox + x, oy + y), INK[ch])
    return im.resize((size * scale, size * scale), Image.NEAREST)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sheet = Image.new('RGBA', (len(ICONS) * 48 + 8, 56), (22, 41, 61, 255))
    for i, (name, text) in enumerate(ICONS.items()):
        im = render(grid(text))
        im.save(OUT / (name + '.png'))
        big = im.resize((im.width * 1, im.height * 1), Image.NEAREST)
        sheet.alpha_composite(big, (8 + i * 48, 10))
    sheet = sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST)
    sheet.save(OUT.parent / 'icons_sheet.png')
    print('icons', len(ICONS), '->', OUT)


if __name__ == '__main__':
    main()
